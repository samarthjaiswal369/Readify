import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { Document, Packer, Paragraph, TextRun } from 'docx';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const DEFAULT_OUTPUT_DIR = path.resolve(__dirname, '../../outputs');

export class DocumentExportError extends Error {
  constructor(message, code = 'EXPORT_ERROR') {
    super(message);
    this.name = 'DocumentExportError';
    this.code = code;
  }
}

function prepareText(text) {
  if (typeof text !== 'string') {
    throw new DocumentExportError(
      'Invalid document content. Expected text.',
      'INVALID_TEXT'
    );
  }

  const normalized = text.replace(/\r\n?/g, '\n');

  if (!normalized.trim()) {
    throw new DocumentExportError(
      'Cannot generate a document with empty text.',
      'EMPTY_TEXT'
    );
  }

  return normalized;
}

async function saveOutput(extension, content, outputDir) {
  const directory = path.resolve(outputDir || DEFAULT_OUTPUT_DIR);
  const filename = `${crypto.randomUUID()}.${extension}`;

  const finalPath = path.join(directory, filename);
  const temporaryPath = path.join(
    directory,
    `.${crypto.randomUUID()}.tmp`
  );

  await fs.mkdir(directory, { recursive: true });

  try {
    await fs.writeFile(temporaryPath, content, {
      flag: 'wx',
      mode: 0o600
    });

    await fs.rename(temporaryPath, finalPath);

    const stats = await fs.stat(finalPath);

    return {
      fileName: filename,
      filePath: finalPath,
      fileSize: stats.size
    };
  } catch (error) {
    await fs.rm(temporaryPath, { force: true }).catch(() => {});

    throw new DocumentExportError(
      `Failed to save ${extension.toUpperCase()} output: ${error.message}`,
      'OUTPUT_WRITE_FAILED'
    );
  }
}

export async function generateTxt(text, options = {}) {
  const normalized = prepareText(text);
  const content = Buffer.from(normalized, 'utf8');

  return saveOutput(
    'txt',
    content,
    options.outputDir
  );
}

export async function generateDocx(text, options = {}) {
  const normalized = prepareText(text);

  const safeText = normalized.replace(
    /[\u0000-\u0008\u000B\u000C\u000E-\u001F\uFFFE\uFFFF]/g,
    ''
  );

  const paragraphs = safeText.split('\n').map(line => {
    return new Paragraph({
      children: line.length
        ? [new TextRun({ text: line })]
        : []
    });
  });

  try {
    const document = new Document({
      creator: 'Readify',
      title: options.title || 'Readify Machine-Readable Document',
      description: 'Document generated by Readify',
      sections: [
        {
          children: paragraphs
        }
      ]
    });

    const buffer = await Packer.toBuffer(document);

    return await saveOutput(
      'docx',
      buffer,
      options.outputDir
    );
  } catch (error) {
    if (error instanceof DocumentExportError) {
      throw error;
    }

    throw new DocumentExportError(
      `Failed to generate DOCX: ${error.message}`,
      'DOCX_GENERATION_FAILED'
    );
  }
}

export default {
  generateTxt,
  generateDocx,
  DocumentExportError
};
